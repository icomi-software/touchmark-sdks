"""Write types.gen.go: the API document's component schemas as Go types.

Usage: python3 scripts/gen_types.py ../openapi/openapi.json types.gen.go
The output is passed through gofmt by scripts/generate.sh.
"""

import json
import sys
from typing import Any

INITIALISMS = {
    "api": "API",
    "asn": "ASN",
    "bimi": "BIMI",
    "dkim": "DKIM",
    "dmarc": "DMARC",
    "dns": "DNS",
    "e164": "E164",
    "id": "ID",
    "ip": "IP",
    "ips": "IPs",
    "mx": "MX",
    "rpt": "RPT",
    "spf": "SPF",
    "sts": "STS",
    "tls": "TLS",
    "url": "URL",
}


def go_name(name: str) -> str:
    return "".join(INITIALISMS.get(part, part.capitalize()) for part in name.split("_"))


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[1]


def nullable(schema: dict[str, Any]) -> dict[str, Any] | None:
    """The non-null part of an ``anyOf: [X, null]``, else None."""
    options = schema.get("anyOf")
    if not options or len(options) != 2:
        return None
    rest = [option for option in options if option.get("type") != "null"]
    return rest[0] if len(rest) == 1 else None


def go_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return ref_name(schema["$ref"])
    inner = nullable(schema)
    if inner is not None:
        return "*" + go_type(inner)
    kind = schema.get("type")
    if kind == "array":
        return "[]" + go_type(schema["items"])
    if kind == "object":
        return "map[string]" + go_type(schema.get("additionalProperties", {}))
    scalar = {"string": "string", "integer": "int", "number": "float64", "boolean": "bool"}
    if kind in scalar:
        return scalar[kind]
    raise SystemExit(f"unsupported schema: {json.dumps(schema)}")


def comment(text: str, indent: str = "") -> list[str]:
    return [f"{indent}// {line}".rstrip() for line in text.strip().splitlines()]


def main() -> None:
    source, target = sys.argv[1:3]
    schemas = json.load(open(source))["components"]["schemas"]
    out = [
        "// Code generated by scripts/gen_types.py from openapi/openapi.json; DO NOT EDIT.",
        "",
        "package touchmark",
        "",
    ]
    for name in sorted(schemas):
        schema = schemas[name]
        description = schema.get("description")
        if "enum" in schema:
            if description:
                out += comment(description)
            out += [f"type {name} string", "", "const ("]
            out += [f'\t{name}{go_name(str(value))} {name} = "{value}"' for value in schema["enum"]]
            out += [")", ""]
            continue
        if description:
            out += comment(description)
        out.append(f"type {name} struct {{")
        required = set(schema.get("required", []))
        for field, prop in schema.get("properties", {}).items():
            if prop.get("description"):
                out += comment(prop["description"], "\t")
            tag = field if field in required else f"{field},omitempty"
            out.append(f'\t{go_name(field)} {go_type(prop)} `json:"{tag}"`')
        out += ["}", ""]
    with open(target, "w") as file:
        file.write("\n".join(out))


if __name__ == "__main__":
    main()
